// FILE: src/app/api/backup/[id]/download/route.ts
//
// GET — download one backup file (ADMIN only: backup:write). The file comes
// from Supabase Storage ("supabase:…" references) or from BACKUP_DIR on a
// self-hosted server (older, plain file-name references); see
// readBackupFile in src/lib/backup.ts.
import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/db";
import { requirePermission } from "@/lib/session";
import { withErrorHandling, ApiError } from "@/lib/api-handler";
import { readBackupFile, BackupError, BackupFileMissingError } from "@/lib/backup";

export const runtime = "nodejs";
export const maxDuration = 60;

export const GET = withErrorHandling(async (req: NextRequest, context) => {
  const auth = await requirePermission("backup:write", req);
  if ("error" in auth) return NextResponse.json({ error: auth.error }, { status: auth.status });

  const { id: idParam } = await context!.params;
  const id = parseInt(idParam);
  if (Number.isNaN(id)) throw new ApiError(400, "INVALID_ID", "Invalid backup id.");

  const backup = await prisma.backup.findUnique({ where: { id } });
  if (!backup || !backup.file_reference) throw new ApiError(404, "NOT_FOUND", "Backup not found.");

  let file;
  try {
    file = await readBackupFile(backup.file_reference);
  } catch (err) {
    if (err instanceof BackupFileMissingError) throw new ApiError(404, "FILE_MISSING", err.message);
    if (err instanceof BackupError) throw new ApiError(400, "BACKUP_UNAVAILABLE", err.message);
    throw err;
  }

  // File names are generated by the server (backup-<timestamp>.json.gz /
  // .sql), but strip quotes anyway so the header can't be broken.
  const safeName = file.filename.replace(/["\\\r\n]/g, "");

  return new NextResponse(file.body as unknown as BodyInit, {
    headers: {
      "Content-Type": file.contentType,
      "Content-Disposition": `attachment; filename="${safeName}"`,
      "Cache-Control": "no-store",
    },
  });
});